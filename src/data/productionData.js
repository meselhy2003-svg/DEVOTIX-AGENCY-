const STORAGE_KEY = 'devotix_production_galleries';

export function getProductionGalleries() {
  if (typeof window === 'undefined') return DEFAULT_PRODUCTION_GALLERIES;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to parse production galleries from localStorage:', e);
  }
  return DEFAULT_PRODUCTION_GALLERIES;
}

export function saveProductionGalleries(galleries, syncCloud = true) {
  if (typeof window === 'undefined') return;
  try {
    if (!Array.isArray(galleries) || galleries.length === 0) {
      console.warn('saveProductionGalleries: ignored empty or invalid array');
      return;
    }
    localStorage.setItem(STORAGE_KEY, JSON.stringify(galleries));
    window.dispatchEvent(new CustomEvent('devotix_production_updated', { detail: galleries }));
    if (syncCloud) {
      import('../services/cmsSync').then(({ pushKeyToCloud, CMS_KEYS }) => {
        pushKeyToCloud(CMS_KEYS.PRODUCTION, galleries);
      }).catch(() => {});
    }
  } catch (e) {
    console.error('Failed to save production galleries to localStorage:', e);
  }
}

export function resetProductionGalleries() {
  if (typeof window === 'undefined') return;
  try {
    localStorage.removeItem(STORAGE_KEY);
    window.dispatchEvent(new CustomEvent('devotix_production_updated', { detail: DEFAULT_PRODUCTION_GALLERIES }));
  } catch (e) {
    console.error('Failed to reset production galleries in localStorage:', e);
  }
}
