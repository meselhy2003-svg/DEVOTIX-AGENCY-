export function getSavedCampaigns() {
  if (typeof window === 'undefined') return CAMPAIGNS_DATA;
  try {
    const local = localStorage.getItem('devotix_campaigns');
    if (local) {
      const parsed = JSON.parse(local);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to parse campaigns from localStorage:', e);
  }
  return CAMPAIGNS_DATA;
}

export const getCampaignsData = getSavedCampaigns;

export function saveCampaignsData(campaigns, syncCloud = true) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('devotix_campaigns', JSON.stringify(campaigns));
    window.dispatchEvent(new CustomEvent('devotix_campaigns_updated', { detail: campaigns }));
    if (syncCloud) {
      import('../services/cmsSync').then(({ pushKeyToCloud, CMS_KEYS }) => {
        pushKeyToCloud(CMS_KEYS.CAMPAIGNS, campaigns);
      }).catch(() => {});
    }
  } catch (e) {
    console.error('Failed to save campaigns to localStorage:', e);
  }
}

export function resetCampaignsData() {
  if (typeof window === 'undefined') return;
  try {
    localStorage.removeItem('devotix_campaigns');
    window.dispatchEvent(new CustomEvent('devotix_campaigns_updated', { detail: CAMPAIGNS_DATA }));
  } catch (e) {
    console.error('Failed to reset campaigns in localStorage:', e);
  }
}

